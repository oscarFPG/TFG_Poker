    private void nextButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_nextButtonActionPerformed
       
        if ( contTable == FINAL_NUMBER_CARDS){
            nextButton.setEnabled(false);
        }
       
        if (contTable == EMPTY_BOARD){
           setContTable(INITIAL_NUMBER_CARDS);
            board.nextCard(this.contTable);
        }
        else{
            setContTable(this.contTable + 1);
            board.nextCard(this.contTable);
        }
        
        if (omaha) { board.equityOmaha(this.contTable); }
        else { board.equity(this.contTable); }
        
        this.commonCards = board.getNextCards();
        actualizarGUI();
        this.revalidate();
        this.repaint();
    }//GEN-LAST:event_nextButtonActionPerformed


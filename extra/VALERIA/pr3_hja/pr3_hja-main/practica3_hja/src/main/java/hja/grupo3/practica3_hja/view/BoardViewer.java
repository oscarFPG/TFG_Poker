    public BoardViewer(Board board, int numJugadores, Player[] players, Card[] commonCards) {
        
        //-----CONSTRUCTOR----
        this.board = board;
        this.contTable = 0;
        this.lista = new cartasPanel[players.length];
  
        this.omaha = this.board.getOmaha();
        if (omaha) { this.board.equityOmaha(0);}
        else { this.board.equity(0); }
        this.numJugadores = numJugadores;
        this.players = players;
        this.commonCards = commonCards;
        initComponents();
        setVisible(true);
        this.setLocationRelativeTo(null);
        
        //------FONDO------------
        BackGroundPanel panelFondo = new BackGroundPanel();
        this.setContentPane(panelFondo);
        
        //-------CARTAS-----------
        if (players != null){
            dibujarCartasJugadores();
            dibujarCartasMesa();
        }
       
        getContentPane().add(nextButton);
        getContentPane().add(backButton);
        
        
    }
    
    public void dibujarCartasMesa(){
        int X = this.getWidth() / 3 - 20;
        int Y = this.getHeight() / 3 + 40;
        this.cartasBoardPanel = new cartasPanel(this,"",commonCards, 0, false);
        this.cartasBoardPanel.setBounds(X, Y, 400,225); 
        getContentPane().add(cartasBoardPanel);
    }
    
     public void dibujarCartasJugadores(){
        int centroX = (this.getWidth() / 3)+ 60;
        int centroY = (this.getHeight() / 3);
        double radioX = 400; // Radio horizontal del óvalo
        double radioY = 250; // Radio vertical del óvalo
           
        double angulo = 2 * Math.PI / numJugadores;
         for (int i = 0; i < numJugadores; i++) {
            cartasPanel cartasPanel = new cartasPanel(this,players[i].getID(), players[i].getCards(), players[i].getEquity(),omaha);
            double x = centroX + radioX * Math.cos(i * angulo) - cartasPanel.getWidth() / 2;
            double y = centroY + radioY * Math.sin(i * angulo) - cartasPanel.getHeight() / 2;
            if(omaha) {
                cartasPanel.setBounds((int) x, (int) y - 30, 200, 320); 
            }
            else {
                cartasPanel.setBounds((int) x, (int) y, 200, 225); 
            }
             lista[i] = cartasPanel;
             getContentPane().add(cartasPanel);
        }  
    }
     
    public void addCard(Card[] card){
        for ( int i = 0; i < card.length; i++){
            board.addCard(card[i]);
        }
    }
    
